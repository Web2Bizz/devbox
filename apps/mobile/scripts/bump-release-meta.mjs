#!/usr/bin/env node
// Second half of the auto-bump (runs after scripts/bump-version.mjs):
// brings the native release metadata in lockstep with the new package.json
// version so `npm run check:versions` stays green on the bump commit.
//
//   1. versionCode +1 in app.json — monotonic ACROSS majors, never reset
//      (Play/F-Droid key upgrades off it; the version NAME reset on main
//      must not touch it).
//   2. Reuses scripts/sync-version.mjs for app.json version + gradle
//      versionName (imported for its side effect, after the code bump).
//   3. Creates stub changelogs for the new versionCode when missing
//      (distribution + fastlane): first line pins v<version> as
//      check-version-parity.mjs requires; body is an explicit TODO for the
//      release author — never ship a stub to a store.
//
// Usage: node scripts/bump-release-meta.mjs [--dry-run]
import { readFile, writeFile, mkdir } from "node:fs/promises"
import path from "node:path"

export function nextVersionCode(code) {
  const n = Number(code)
  if (!Number.isInteger(n) || n < 1) throw new Error(`Invalid versionCode '${code}' (expected a positive integer)`)
  return n + 1
}

export function changelogStub(version) {
  return `v${version}\n(Changelog pending — fill in before release.)\n`
}

// android/ is generated by `expo prebuild` (which rewrites this line from
// app.json), but CI's check:versions runs without a prebuild — patch the
// single versionCode line so the bump commit is green on its own.
export function syncGradleVersionCode(gradle, code) {
  const next = gradle.replace(/^(\s*versionCode\s+)\d+/m, `$1${code}`)
  if (next === gradle) throw new Error("versionCode line not found in android/app/build.gradle")
  return next
}

async function writeStubIfMissing(file, version, dryRun) {
  try {
    await readFile(file, "utf8")
    console.error(`kept ${file} (already exists)`)
  } catch {
    if (!dryRun) {
      await mkdir(path.dirname(file), { recursive: true })
      await writeFile(file, changelogStub(version), "utf8")
    }
    console.error(`stub ${file}`)
  }
}

async function run() {
  const dryRun = process.argv.includes("--dry-run")
  const root = process.cwd()

  const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"))
  if (!pkg.version) throw new Error("Field version is missing in package.json")

  const appPath = path.join(root, "app.json")
  const app = JSON.parse(await readFile(appPath, "utf8"))
  const code = nextVersionCode(app.expo?.android?.versionCode)
  if (!dryRun) {
    app.expo.android.versionCode = code
    await writeFile(appPath, JSON.stringify(app, null, 2) + "\n", "utf8")
  }
  console.error(`versionCode → ${code}${dryRun ? " (dry-run)" : ""}`)

  if (!dryRun) {
    // Runs the package.json → app.json version + gradle versionName sync.
    await import("./sync-version.mjs")
    const gradlePath = path.join(root, "android", "app", "build.gradle")
    const gradle = await readFile(gradlePath, "utf8")
    await writeFile(gradlePath, syncGradleVersionCode(gradle, code), "utf8")
    console.error(`android/app/build.gradle versionCode → ${code}`)
  } else {
    console.error("sync-version.mjs skipped (dry-run)")
  }

  await writeStubIfMissing(path.join(root, "distribution", "changelogs", `${code}.txt`), pkg.version, dryRun)
  await writeStubIfMissing(
    path.join(root, "fastlane", "metadata", "android", "en-US", "changelogs", `${code}.txt`),
    pkg.version,
    dryRun,
  )

  console.log(`${pkg.version} (${code})`)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname
if (isMain) {
  run().catch((e) => {
    console.error(`${e.message}`)
    process.exit(1)
  })
}
